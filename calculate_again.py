def add(a, b):
    return a + b

    
def subtract(a, b):
    return a - b


def multiply(a, b):
    return a * b

def divid(a, b):
    return a / b

def calculate_price():
        kayla = add(10, 5)
        op = subtract(50, 25)
        rice = multiply(30, 3)
        nunu = divid(100, 20)
        final_output = kayla + op + rice + nunu
        print(final_output)

calculate_price()